/**
 * **内行词表 —— 唯一权威位置**（2026-09-22 主人裁决：设计词汇给设计者，界面语言给用户）。
 *
 * ## 为什么单独一个文件
 *
 * 这份词表原先**只写在 `verify-ui.mjs` 里**，而那是一支**要真机 core + token + 喂过的世界**
 * 才跑得起来的页面级脚本 —— 它**不在 `npm run verify` 里**，并且**已经很久没被跑过**
 * （2026-09-26 首次实跑，才发现它整段陈旧）。
 *
 * 代价是实测出来的：前端大整改 B2 一次就扫出 **13 处内行词上屏**
 * （`aria-label="Core Bearer token"`、`本机受管 Runtime`、`准入`、`读数`……），
 * 而**没有任何门禁拦得住它们** —— `check-voice.mjs` 管的是人称代词，不是这份表。
 * 换句话说：**规则一直写着，判据一直没人跑。**
 *
 * 现在词表住在这里，**两个执行者共用同一份**：
 *
 * | 执行者 | 怎么跑 | 判据落在哪 | 要不要真机 |
 * |---|---|---|---|
 * | `probe.mjs` 的 `sweep` | `npm run verify`（自动） | **渲染后的正文**（逐条路由） | **不要** |
 * | `verify-ui.mjs` | `npm run verify:ui`（手动） | **渲染后的正文**（带 token 的真实世界） | 要 |
 *
 * ⚠ **别把词表抄回任何一个执行者**：抄回去就是两个权威，它们一定会漂
 * （实测漂过：`Core`/`Runtime` 在这张表里从来没有过，而规则正文一直把它们列在禁用词里）。
 *
 * ## ⚠ 两个执行者共同的**盲区**：交互之后才出现的文案（2026-10-08 记账）
 *
 * 两个执行者读的都是**默认渲染**：`sweep` 把路由打开就扫，`verify-ui` 也一样。
 * 于是**点了才出现的那几句谁也看不到** —— 实测：外观页「我的主题」在刀 1 漏过一个
 * 「读数」（那正是"装完才渲染"的一句），而 `npm run verify` 一路全绿。
 *
 * ⇒ 交互后才渲染的文案要**自己带判据**：见 `tests/user-theme.test.ts` 的
 * 「交互之后才出现的那几句也不许有内行词」（**词表仍然取这一份**，只是判据落在源码上、
 * 先摘注释再扫）。**这不是替换上面两个执行者，是补它们的盲区。**
 *
 * ## 判据的形状
 *
 * 读的是**渲染后的正文**，不是源码 ⇒ **天然只覆盖用户可见面**：注释里照旧可以用这些词
 * （那是给开发者读的，`DESIGN_SYSTEM.md` 明说合法）。这是它比"扫源码"更准的地方 ——
 * 也是它**必须**留在页面级脚本里的原因。
 */

/**
 * 内行词。每一条都是**设计者/维护者内部词汇**，用户语言里各有说法
 * （清醒→活动、准入→能不能开始、读数→状态、入籍→创建……）。
 */
export const JARGON = [
  '清醒',
  '唤醒',
  '准入',
  '收场',
  '读数',
  '管家',
  '门铃',
  '答话',
  '在岗',
  '标称窗口',
  '线协议',
  '摘除',
  // 用户语言里它就叫「创建」。
  '入籍',
  // ⚠ 2026-09-26 补：规则正文（`DESIGN_SYSTEM.md`）**一直**把内部组件名列在禁用词里，
  // 而这张表里**从来没有它们** ⇒ 13 处 `Core`/`Runtime` 上屏一条都拦不住。
  // **规则比判据宽**是这条守卫最大的漏洞，补上。
  'Core',
  'Runtime',
]

/**
 * 这些路由**豁免**本判据 —— 逐条点名并写清依据，不做前缀模糊匹配。
 *
 * `probe sweep` 会把全部路由都渲染一遍，所以豁免必须显式。
 */
export const JARGON_EXEMPT_PATHS = new Set([
  // 陈列室是**给设计者的参照页**（`DESIGN_SYSTEM.md` 明说它不属于"用户可见面"）：
  // 里面有一张讲分层架构的 mermaid 图，源码里就写着 `B --> C[Core]`。
  '/gallery',
])

/** 这一段正文里漏出来的内行词（空数组 = 干净）。 */
export function leakedJargon(text, routePath = null) {
  if (routePath && JARGON_EXEMPT_PATHS.has(routePath)) return []
  const haystack = String(text ?? '')
  return JARGON.filter((word) => haystack.includes(word))
}
