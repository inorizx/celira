/**
 * **已撤销的 Agent 不该有一张"可操作"的页**（2026-10-20 T3 一刀）。
 *
 * ## 它治的是什么
 *
 * 撤销是**软撤销**（契约：不硬删除，`revoked` 那一支仍留在所有权清单里，历史照旧）。
 * 列表那一行早就改过来了（2026-09-29：不再画三格，就地说明后果）—— 但**深链接**
 * `/app/agents/<已撤销 id>` 进来仍然是一张完整的管理台：接入、签发凭证、接到机器上、
 * 选模型、撤销 Agent **全都在**。两处说同一件事的页面给出两个相反的答案（这一页说
 * "还能操作"，列表那一行说"它不接收事件了"）。
 *
 * ## 判据
 *
 * 一句话：**撤销之后还剩什么能改？** 什么都改不了 —— 凭证作废、绑定作废、房间成员关系
 * 作废、世界那一侧也不再接受它的事件。所以这一页剩下的**不是**"管理台的只读版"，
 * 而是**一条后果说明 ＋ 一个返回**：那正是列表那一行已经在说的那一句。
 *
 * ⚠ 判据在这里、不在页面里：页面那一层没有用例（React 不进 `node --test`），
 * 而"这一支还该不该渲染管理面"是一条**能不能写**的判据（同 `uiPolicy.ts` 的那一族）。
 *
 * 纯函数、零副作用 ⇒ `node --test` 直测（`tests/agent-revoked.test.ts`）。
 */

import type { OwnedAgent } from './domain.ts'

/**
 * 撤销之后那句**后果说明** —— **全仓唯一一处字面量**。
 *
 * 两处渲染它（列表那一行 / 深链接那一页），一个字都不许各写一遍：
 * 同一件事两个说法，用户会以为是两件事（而且改一处忘一处是必然的）。
 */
export const AGENT_REVOKED_CONSEQUENCE =
  '已撤销 —— 不再接收事件，房间成员关系与凭证一并作废'

/**
 * 这一支还该不该渲染**管理面**（接入 / 凭证 / 撤销 / 接上 / 模型）。
 *
 * 判据只有一格：`revoked`。⚠ 缺省（老响应没这一格）按**活着**处理 —— 那是既有口径
 * （`AgentsListPanel` 里 `participant.revoked ? … : …` 一直是这么读的），把它当"已撤销"
 * 会让一次响应缺字段就把整页关掉。
 */
export function shouldShowAgentAdmin(agent: Pick<OwnedAgent, 'revoked'>): boolean {
  return agent.revoked !== true
}
