//! 主体进行态的领域常量（契约 `CORE_V1_AGENT_PROTOCOL.md` §6）。
//!
//! 本模块只有**生命周期与边界**：两个 TTL 与两张进程内表的硬上限。它不
//! 定义任何持久事实，也不定义任何执行面概念（阶段 / 生成流 / 草稿正文
//! 已于 2026-09-28 随旧 Live State 删除）。

use std::time::Duration;

/// 「我正在这间房写」的有效期：这么久没有新的 typing 就被视为没在写。
///
/// 取值理由：比"打字停顿"长（想一句话中间停顿不该闪断），比"一条消息的
/// 正常起草时间"短（不要让人一直亮着）。客户端按 ≤1/3 TTL 的节奏续报，
/// 具体节奏归客户端，契约只认这个上限。
pub const TYPING_TTL: Duration = Duration::from_millis(6_000);

/// 「最近一次被看见」的有效期：拉取式 Backend（不挂门铃）停止活动后，
/// 最多这么久内仍可能被判为在线。
///
/// 这是"最近被看见"的固有代价，写进契约：它不是心跳，而是认证路径的
/// 副产品；真要在秒级精确，就该挂门铃——连接断了条目立刻消失。
pub const SEEN_TTL: Duration = Duration::from_millis(60_000);

/// `last_seen` 表的硬上限（进程内）。达到上限时按时间最旧优先淘汰——
/// 这是易失信号，淘汰不报错、不产生错误码（丢一条"最近被看见"不影响任何
/// 公共事实）。
pub const MAX_SEEN_ENTRIES: usize = 8_192;

/// `typing` 表的硬上限（进程内）。同上：丢一条进行态不影响任何公共事实。
pub const MAX_TYPING_ENTRIES: usize = 4_096;
